let loading = null;
/** Loads the catalog once (the first time the Finish step opens); resolves with it, or rejects offline. */
function loadData() {
  if (root.EGCGameplanVehicleData) return Promise.resolve(root.EGCGameplanVehicleData);
  if (loading) return loading;
  loading = new Promise((resolve, reject) => {
    const script = root.document.createElement('script');
    script.src = DATA_URL; script.async = true;
    script.onload = () => root.EGCGameplanVehicleData ? resolve(root.EGCGameplanVehicleData) : reject(new Error('empty'));
    script.onerror = () => { script.remove(); loading = null; reject(new Error('unavailable')); };
    root.document.head.append(script);
  });
  return loading;
}
const h = (tag, attrs, ...children) => {
  const node = root.document.createElement(tag);
  for (const [key, value] of Object.entries(attrs || {})) {
    if (value == null || value === false) continue;
    if (key === 'class') node.className = value; else if (key.startsWith('on')) node.addEventListener(key.slice(2), value);
    else if (key in node && !key.startsWith('aria-') && !key.startsWith('data-')) node[key] = value; else node.setAttribute(key, String(value));
  }
  for (const child of children.flat(Infinity)) if (child != null && child !== false) node.append(child instanceof root.Node ? child : String(child));
  return node;
};
