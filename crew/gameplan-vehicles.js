const CONFIDENCE = ['high', 'medium', 'low', 'typical', 'measured'];

const round1 = n => Math.round(n * 10) / 10;
const r = n => String(Math.round(n));
const plain = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const worst = list => list.reduce((a, b) => STATUS.indexOf(b) > STATUS.indexOf(a) ? b : a, 'fits');
function feet(inches) {
  let ft = Math.floor(inches / 12), rest = round1(inches - ft * 12);
  if (rest >= 12) { ft += 1; rest = round1(rest - 12); }
  return rest ? `${ft} ft ${rest} in` : `${ft} ft`;
}

/** A length typed as feet and inches or inches: "20' 4\"", "20 ft 4", "20ft4in", "6' 8 1/2\"", "244", "244 in", "20.3 ft".
 * A bare number up to 30 is feet when that is a plausible size here (a garage depth of "20"), else inches (a motorcycle
 * "30" wide). Returns null for blank, {error} when unreadable or outside the limits [min, max], else {inches,
 * assumedFeet, text: what was understood}. */
function parseLength(raw, limits = [1, 2000]) {
  const typed = String(raw ?? '').trim();
  if (!typed) return null;
  const s = typed.toLowerCase().replace(/[\u2019\u2032\u2018`\u00b4]/g, '\'').replace(/[\u201d\u2033\u201c]/g, '"').replace(/''/g, '"')
    .replace(/(?<![a-z])(?:feet|foot|ft)(?![a-z])\.?/g, '\'').replace(/(?<![a-z])(?:inches|inch|in)(?![a-z])\.?/g, '"')
    .replace(/'\s*-\s*/g, '\' ').replace(/\s*(['"])\s*/g, '$1 ').replace(/\s+/g, ' ').trim();
  const NUM = String.raw`(\d+(?:\.\d+)?|\.\d+)`, FRAC = String.raw`(?: (\d+)\/(\d+))?`;
  const part = (a, b) => a && b && Number(b) > 0 ? Number(a) / Number(b) : 0;
  let m, inches, assumedFeet = false;
  if ((m = new RegExp(`^${NUM}' ?(?:${NUM}${FRAC} ?"?)?$`).exec(s))) inches = Number(m[1]) * 12 + (m[2] ? Number(m[2]) : 0) + part(m[3], m[4]);
  else if ((m = new RegExp(`^${NUM}${FRAC} ?"$`).exec(s))) inches = Number(m[1]) + part(m[2], m[3]);
  else if ((m = /^(\d+) (\d+(?:\.\d+)?)$/.exec(s)) && Number(m[1]) <= 30 && Number(m[2]) < 12) inches = Number(m[1]) * 12 + Number(m[2]);
  else if ((m = new RegExp(`^${NUM}${FRAC}$`).exec(s))) { const n = Number(m[1]) + part(m[2], m[3]); assumedFeet = n <= 30 && n * 12 >= limits[0] && n * 12 <= limits[1]; inches = assumedFeet ? n * 12 : n; }
  else return { error: 'Not understood: type feet and inches (20\' 4") or inches (244).' };
  inches = round1(inches);
  const [min, max] = limits;
  if (!(inches >= min && inches <= max)) return { error: `${r(inches)} in looks wrong here (expected ${feet(min)} to ${feet(max)}): check it.` };
  return { inches, assumedFeet, text: assumedFeet ? `Read as ${feet(inches)} = ${inches} in` : `= ${inches} in (${feet(inches)})` };
}
const measuredValue = (measure, key) => { const parsed = plain(measure) ? parseLength(measure[key], LIMITS[key]) : null; return parsed && !parsed.error ? parsed.inches : null; };

/** The garage the fit check uses: each measured dimension, else the typical one for the garage size, marked typical. */
function garageFrom(size, measure = {}) {
  const key = Object.hasOwn(TYPICAL_GARAGE, size) && size !== 'ceiling' ? String(size) : '2', typical = TYPICAL_GARAGE[key];
  const dim = (name, fallback) => { const value = measuredValue(measure, name); return value === null ? { in: fallback, typical: true } : { in: value, typical: false }; };
  const door = measuredValue(measure, 'doorWidth');
  return { size: key, width: dim('width', typical.width), depth: dim('depth', typical.depth), doors: door === null ? typical.doors.map(w => ({ in: w, typical: true })) : [{ in: door, typical: false }],
    doorHeight: dim('doorHeight', typical.doorHeight), ceiling: dim('ceiling', TYPICAL_GARAGE.ceiling) };
}
/** Only what the estimator measured, as scope.garage_measurements ({width_in, depth_in, ...}), or null. */
function measuredGarage(measure) {
  const out = {};
  for (const [key, name] of [['width', 'width_in'], ['depth', 'depth_in'], ['doorWidth', 'door_width_in'], ['doorHeight', 'door_height_in'], ['ceiling', 'ceiling_in']]) {
    const value = measuredValue(measure, key);
    if (value !== null) out[name] = value;
  }
  return Object.keys(out).length ? out : null;
}

// The size class a catalog row belongs to (its mirror allowance when the source has no width across the mirrors).
function classOf(body, length, width) {
  if (body === 'car' || body === 'wagon') return length < 188 ? 'compact_car' : length < 196 ? 'midsize_car' : 'fullsize_car';
  if (body === 'suv') return width >= 79 || length >= 205 ? (length >= 218 ? 'extended_fullsize_suv' : 'fullsize_suv') : length >= 188 ? 'midsize_suv' : 'small_suv';
  if (body === 'minivan') return 'minivan';
  if (body === 'pickup') return width < 72 ? 'compact_pickup' : width < 78 ? 'midsize_pickup_crew' : length < 245 ? 'fullsize_pickup_crew_short' : 'fullsize_pickup_crew_long_hd';
  if (body === 'van') return length < 200 && width < 76 ? 'minivan' : 'fullsize_van';
  return '';
}
const truckLike = body => ['pickup', 'van', 'suv'].includes(body);

/** A vehicle as the walkthrough keeps it (S.customerVehicles), or null when it cannot be used. */
function cleanVehicle(value) {
  if (!plain(value) || !Object.hasOwn(SOURCES, value.source)) return null;
  const num = (x, [min, max]) => typeof x === 'number' && Number.isFinite(x) && x >= min && x <= max ? round1(x) : null;
  const length = num(value.length_in, LIMITS.length), width = num(value.width_in, LIMITS.vehicleWidth), height = num(value.height_in, LIMITS.height);
  if (length === null || width === null || height === null) return null;
  const mirrors = num(value.width_mirrors_in, [width, 170]), label = String(value.label || '').replace(/\s+/g, ' ').trim().slice(0, 120) || SOURCES[value.source];
  return { label, short: String(value.short || '').replace(/\s+/g, ' ').trim().slice(0, 60) || label, source: value.source, id: String(value.id || '').slice(0, 120),
    length_in: length, width_in: width, height_in: height, width_mirrors_in: mirrors ?? round1(width + (value.truck ? ROOM.mirrorTruck : ROOM.mirrorCar)),
    mirrors: ['listed', 'estimated', 'measured'].includes(value.mirrors) ? value.mirrors : mirrors === null ? 'estimated' : 'listed',
    confidence: CONFIDENCE.includes(value.confidence) ? value.confidence : value.source === 'catalog' ? 'medium' : value.source,
    measure: value.measure === true, note: String(value.note || '').slice(0, 300) };
}
/** The plain object scope.customer_vehicles carries. */
const scopeVehicle = v => ({ label: v.label, source: v.source, length_in: v.length_in, width_in: v.width_in, height_in: v.height_in, width_mirrors_in: v.width_mirrors_in, confidence: v.confidence });

// ---- The catalog (crew/gameplan-vehicles-data.js) --------------------------------------------------------------------
const slug = text => String(text).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const rowId = (data, i) => data.ids?.[i] || slug(`${data.makes[data.rows[i][0]]} ${data.rows[i][1]} ${data.rows[i][2]} ${data.rows[i][3]} ${data.rows[i][6]}`);
const rowNote = (data, i) => data.notes[data.rows[i][12]] || '';
const sizeClass = (data, key) => (data?.classes || []).find(item => item.key === key) || null;
/** The vehicle a catalog row stands for; year: the model year searched for, when the row covers it. */
function fromRow(data, i, year = null) {
  const [make, model, from, to, , body, config, length, width, height, mirrors, confidence] = data.rows[i];
  const makeName = data.makes[make], bodyName = data.bodies[body], note = rowNote(data, i), cls = sizeClass(data, classOf(bodyName, length, width));
  const allowance = cls ? cls.mirrorAllowance : truckLike(bodyName) ? ROOM.mirrorTruck : ROOM.mirrorCar, level = data.confidence[confidence];
  const covered = Number.isInteger(year) && year >= from && year <= to ? year : null;
  return cleanVehicle({ label: `${covered ? `${covered} ` : ''}${makeName} ${model}${config ? ` ${config}` : ''}${covered ? '' : ` (${from === to ? from : `${from}–${to}`})`}`,
    short: model, source: 'catalog', id: rowId(data, i), length_in: length, width_in: width, height_in: height, width_mirrors_in: mirrors || round1(width + allowance),
    mirrors: mirrors ? 'listed' : 'estimated', confidence: level, measure: level === 'low' || /measure/i.test(note), note });
}
/** The typical vehicle of a size class ("Not in the list?"). */
function fromClass(cls) {
  const name = String(cls.name), short = name.replace(/\s*\(.*\)$/, '').toLowerCase();
  return cleanVehicle({ label: `${name}, typical size`, short, source: 'typical', id: cls.key, length_in: cls.length, width_in: cls.width, height_in: cls.height, width_mirrors_in: cls.widthMirrors, mirrors: 'estimated', confidence: 'typical' });
}
/** A vehicle the estimator measured: width is the body ('car' adds 9 in for mirrors, 'truck' 12 in) or 'mirrors' (across them). */
function fromMeasure({ name = '', length, width, height, basis = 'car' } = {}) {
  const read = (value, key) => { const parsed = parseLength(value, LIMITS[key]); return parsed && !parsed.error ? parsed.inches : null; };
  const L = read(length, 'length'), W = read(width, 'vehicleWidth'), H = read(height, 'height');
  if (L === null || W === null || H === null) return null;
  const label = String(name || '').trim() || 'Measured vehicle';
  return cleanVehicle({ label, short: String(name || '').trim() || 'measured vehicle', source: 'measured', length_in: L, width_in: W, height_in: H,
    width_mirrors_in: basis === 'mirrors' ? W : round1(W + (basis === 'truck' ? ROOM.mirrorTruck : ROOM.mirrorCar)), mirrors: basis === 'mirrors' ? 'measured' : 'estimated', confidence: 'measured' });
}

// Search: make, model and year in any order; case, hyphens and spaces do not matter (F-150 = F150 = f 150), and common
// short names find their make (Chevy, VW, Benz, Olds, Caddy; a Ram is found as a Dodge too).
const MAKE_WORDS = Object.freeze({ Chevrolet: 'chevy chev', Volkswagen: 'vw volkswagon', 'Mercedes-Benz': 'mercedes benz mb merc', Oldsmobile: 'olds', Cadillac: 'caddy caddie',
  Ram: 'dodge', 'Land Rover': 'landrover', Infiniti: 'infinity', Porsche: 'porche', Hyundai: 'hundai hyundia', Mini: 'cooper', Mitsubishi: 'mitsu', Volvo: '', Toyota: 'yota',
  Chrysler: 'chrystler', Pontiac: 'ponti', Subaru: 'subie', Lincoln: '', International: 'ih harvester', 'Alfa Romeo': 'alfa' });
const BODY_WORDS = Object.freeze({ car: 'car', suv: 'suv', pickup: 'pickup truck', wagon: 'wagon estate', minivan: 'minivan van', van: 'van' });
const norm = text => String(text || '').normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/&/g, ' and ');
const compact = text => norm(text).replace(/[^a-z0-9]/g, '');
const INDEX = new WeakMap();
function indexOf(data) {
  if (INDEX.has(data)) return INDEX.get(data);
  const rows = data.rows.map(row => {
    const make = data.makes[row[0]], text = norm(`${make} ${MAKE_WORDS[make] || ''} ${row[1]} ${row[6]} ${data.generations[row[4]] || ''} ${BODY_WORDS[data.bodies[row[5]]] || ''}`);
    const chunks = text.split(/\s+/).filter(Boolean), words = new Set();
    for (const chunk of chunks) { const whole = chunk.replace(/[^a-z0-9]/g, ''); if (whole) words.add(whole); for (const piece of chunk.split(/[^a-z0-9]+/)) if (piece) words.add(piece); }
    return { words: [...words], compact: chunks.map(chunk => chunk.replace(/[^a-z0-9]/g, '')).join(''), model: norm(row[1]).split(/\s+/).map(chunk => chunk.replace(/[^a-z0-9]/g, '')).filter(Boolean) };
  });
  INDEX.set(data, rows);
  return rows;
}
const YEAR4 = /^(19[5-9]\d|20[0-3]\d)$/;
function tokenScore(token, entry) {
  if (entry.words.includes(token)) return 3;
  if (entry.words.some(word => word.startsWith(token))) return 2;
  return token.length >= 4 && entry.compact.includes(token) ? 1 : 0;
}
/** Catalog rows matching a query, grouped by make, model and generation: {year, groups: [{title, rows: [{index, years,
 * config, dims, measure}]}], total, more}. Newest first; a model year in the query keeps only the rows that cover it. */
function search(data, query, { limit = 30 } = {}) {
  const raw = norm(query).replace(/[\u2019']/g, '').split(/[\s,;/]+/).map(token => token.replace(/[^a-z0-9]/g, '')).filter(Boolean);
  const years = raw.filter(token => YEAR4.test(token)).map(Number), tokens = raw.filter(token => !YEAR4.test(token));
  if (!tokens.length && !years.length) return { year: null, groups: [], total: 0, more: 0 };
  const year = years.length === 1 ? years[0] : null, entries = indexOf(data);
  let hits = [];
  data.rows.forEach((row, index) => {
    if (years.length && !years.some(y => y >= row[2] && y <= row[3])) return;
    let score = 0, rowYear = year, weak = false;
    for (let t = 0; t < tokens.length; t++) {
      const token = tokens[t];
      let s = tokenScore(token, entries[index]);
      // "67 mustang", "15 f150": a two-digit token is a model year unless it is a whole word of the vehicle ("Toyota 86").
      if (s < 3 && /^\d{2}$/.test(token)) {
        const y = Number(token) + (Number(token) >= 50 ? 1900 : 2000);
        if (y >= row[2] && y <= row[3]) { s = 2.5; rowYear = y; } else if (s) weak = true;
      }
      // "rav 4", "cx 5": a short number belongs to the word before it.
      if (t && /^\d{1,3}$/.test(token) && /^[a-z]+$/.test(tokens[t - 1])) { const joined = tokenScore(tokens[t - 1] + token, entries[index]); if (joined === 3 || !s) s = Math.max(s, joined && (joined === 3 ? 3 : 2)); }
      if (!s) return;
      score += s;
    }
    // How much of the model name the words typed cover: "ram" finds the Ram 1500 before the Ram ProMaster.
    const model = entries[index].model, cover = model.reduce((sum, word) => sum + (tokens.some(token => word.startsWith(token)) ? word.length : 0), 0) / (model.join('').length || 1);
    hits.push({ index, score, cover, year: rowYear, weak });
  });
  // When a two-digit token was read as a model year somewhere, rows it only partly spelled ("15" in "150") drop out.
  if (hits.some(hit => hit.year !== year)) hits = hits.filter(hit => !hit.weak);
  hits.sort((a, b) => b.score - a.score || b.cover - a.cover || data.rows[b.index][3] - data.rows[a.index][3] || data.rows[b.index][2] - data.rows[a.index][2] || a.index - b.index);
  const groups = new Map();
  for (const hit of hits.slice(0, limit)) {
    const row = data.rows[hit.index], generation = data.generations[row[4]] || '', key = `${row[0]}|${row[1]}|${row[4]}`;
    if (!groups.has(key)) groups.set(key, { title: `${data.makes[row[0]]} ${row[1]}`, generation, from: row[2], to: row[3], rows: [] });
    const group = groups.get(key);
    group.from = Math.min(group.from, row[2]); group.to = Math.max(group.to, row[3]);
    const level = data.confidence[row[11]];
    group.rows.push({ index: hit.index, year: hit.year, years: row[2] === row[3] ? String(row[2]) : `${row[2]}–${row[3]}`, config: row[6] || ({ suv: 'SUV', pickup: 'Pickup' }[data.bodies[row[5]]] || data.bodies[row[5]].replace(/^./, c => c.toUpperCase())),
      dims: `${r(row[7])} × ${r(row[8])} × ${r(row[9])} in (approx ±2 in)`, measure: level === 'low' || /measure/i.test(rowNote(data, hit.index)) });
  }
  return { year, groups: [...groups.values()].map(group => ({ ...group, years: group.from === group.to ? String(group.from) : `${group.from}–${group.to}` })), total: hits.length, more: Math.max(0, hits.length - limit) };
}

// ---- The fit check ---------------------------------------------------------------------------------------------------
const tag = dim => dim.typical ? ' (typical)' : ' (measured)';
function verdict(status, typical, tightNote = '', wontNote = '') {
  const text = status === 'fits' ? 'fits' : status === 'tight' ? `tight${tightNote}` : `won’t fit${wontNote}`;
  return status !== 'fits' && typical ? `${text}, measure it` : text;
}
/** The parking fit check. garage: garageFrom(); vehicles: what the walkthrough keeps; options: {racks: overhead storage
 * planned, shelving: 'side' | 'back' | null (24 in deep shelves along that wall)}. Returns null without vehicles, else
 * {overall, typical, checks: [{key, label, status, typical, need, have, margin, text}], rackBottom}: each check fits,
 * is tight or won't fit with one plain sentence, and the overall result is the worst check. */
function fitCheck(garage, vehicles, options = {}) {
  const list = (Array.isArray(vehicles) ? vehicles : []).map(cleanVehicle).filter(Boolean);
  if (!list.length || !garage) return null;
  const shelf = ['side', 'back'].includes(options.shelving) ? options.shelving : null, checks = [];
  const add = (key, label, status, typical, need, have, margin, text) => checks.push({ key, label, status, typical, need: round1(need), have: round1(have), margin: round1(margin), text });

  // Depth: the longest vehicle and a walkway in front of it.
  const longest = list.reduce((a, b) => b.length_in > a.length_in ? b : a), depth = garage.depth.in - (shelf === 'back' ? ROOM.shelf : 0);
  const needDepth = longest.length_in + ROOM.walkway, tightDepth = longest.length_in + ROOM.walkwayTight;
  const depthStatus = depth >= needDepth ? 'fits' : depth >= tightDepth ? 'tight' : 'wont_fit';
  add('depth', 'Depth', depthStatus, garage.depth.typical, needDepth, depth, depth - needDepth,
    `Depth: ${r(longest.length_in)} in ${longest.short} + ${ROOM.walkway} in walkway needs ${r(needDepth)} in; garage is ${r(garage.depth.in)} in${tag(garage.depth)}${shelf === 'back' ? ` less ${ROOM.shelf} in of shelving on the back wall = ${r(depth)} in` : ''} — ${depthStatus === 'fits' ? `fits, ${r(depth - needDepth)} in to spare` : verdict(depthStatus, garage.depth.typical, ` (${r(depth - longest.length_in)} in to walk in front)`, ` (even a ${ROOM.walkwayTight} in walkway needs ${r(tightDepth)} in)`)}.`);

  // Width: every vehicle across its mirrors, with room between neighbours and at each side to open the doors.
  const widths = list.map(v => v.width_mirrors_in), sum = widths.reduce((a, b) => a + b, 0), gaps = list.length + 1, width = garage.width.in - (shelf === 'side' ? ROOM.shelf : 0);
  const needWidth = sum + ROOM.gap * gaps, tightWidth = sum + ROOM.gapTight * gaps, widthStatus = width >= needWidth ? 'fits' : width >= tightWidth ? 'tight' : 'wont_fit';
  add('width', 'Width', widthStatus, garage.width.typical, needWidth, width, width - needWidth,
    `Width: ${widths.map(r).join(' + ')} in across the mirrors + ${ROOM.gap} in ${list.length > 1 ? 'between and at each side' : 'at each side'} needs ${r(needWidth)} in; garage is ${r(garage.width.in)} in${tag(garage.width)}${shelf === 'side' ? ` less ${ROOM.shelf} in of shelving on a side wall = ${r(width)} in` : ''} — ${widthStatus === 'fits' ? `fits, ${r(width - needWidth)} in to spare` : verdict(widthStatus, garage.width.typical, ` (${ROOM.gapTight} in gaps need ${r(tightWidth)} in)`, ` (even ${ROOM.gapTight} in gaps need ${r(tightWidth)} in)`)}.`);

  // Door width: each vehicle across its mirrors through the widest door.
  const door = garage.doors.reduce((a, b) => b.in > a.in ? b : a), doorName = garage.doors.length > 1 ? 'the widest door' : 'the door';
  const widest = list.reduce((a, b) => b.width_mirrors_in > a.width_mirrors_in ? b : a), doorRoom = door.in - widest.width_mirrors_in;
  const doorStatus = doorRoom >= ROOM.doorSide ? 'fits' : doorRoom >= ROOM.doorSideTight ? 'tight' : 'wont_fit';
  add('door_width', 'Door width', doorStatus, door.typical, widest.width_mirrors_in + ROOM.doorSide, door.in, doorRoom - ROOM.doorSide,
    `Door width: ${widest.short} is ${r(widest.width_mirrors_in)} in across the mirrors; ${doorName} is ${r(door.in)} in${tag(door)} — ${doorStatus === 'fits' ? `fits, ${r(doorRoom)} in to spare` : verdict(doorStatus, door.typical, `, ${r(doorRoom)} in to spare: fold the mirrors`, door.in - widest.width_in >= ROOM.doorSideTight ? ` with the mirrors out (${r(widest.width_in)} in body: fold the mirrors)` : '')}.`);

  // Door height: the tallest vehicle under the open door.
  const tallest = list.reduce((a, b) => b.height_in > a.height_in ? b : a), headroom = garage.doorHeight.in - tallest.height_in;
  const headStatus = headroom >= ROOM.doorHead ? 'fits' : headroom >= 0 ? 'tight' : 'wont_fit';
  add('door_height', 'Door height', headStatus, garage.doorHeight.typical, tallest.height_in + ROOM.doorHead, garage.doorHeight.in, headroom - ROOM.doorHead,
    `Door height: ${tallest.short} is ${r(tallest.height_in)} in tall; the door opening is ${r(garage.doorHeight.in)} in${tag(garage.doorHeight)} — ${headStatus === 'fits' ? `fits, ${r(headroom)} in to spare` : verdict(headStatus, garage.doorHeight.typical, `, ${r(headroom)} in to spare`, ` (${r(-headroom)} in too tall)`)}.`);

  // Overhead storage: racks hang no lower than the tallest vehicle plus clearance.
  const rackBottom = Math.ceil(tallest.height_in + ROOM.rackClear);
  if (options.racks) {
    const space = garage.ceiling.in - rackBottom, rackStatus = space >= ROOM.rackDrop ? 'fits' : space >= ROOM.rackDropTight ? 'tight' : 'wont_fit';
    add('racks', 'Overhead racks', rackStatus, garage.ceiling.typical, rackBottom + ROOM.rackDrop, garage.ceiling.in, space - ROOM.rackDrop,
      `Overhead racks: ${tallest.short} is ${r(tallest.height_in)} in tall, so racks hang no lower than ${rackBottom} in; the ceiling is ${r(garage.ceiling.in)} in${tag(garage.ceiling)}, which leaves ${r(space)} in — ${verdict(rackStatus, garage.ceiling.typical, ` (most racks need ${ROOM.rackDrop} in, the shortest ${ROOM.rackDropTight} in)`, ' above the vehicles (keep racks out of the parking space)')}.`);
  }
  const overall = worst(checks.map(check => check.status));
  return { overall, typical: checks.some(check => check.typical), checks, rackBottom, shelving: shelf };
}
// The check that limits the parking most: the worst status, then the least room to spare.
const tightest = fit => [...fit.checks].sort((a, b) => STATUS.indexOf(b.status) - STATUS.indexOf(a.status) || a.margin - b.margin)[0];
// A check that is tight or won't fit, in a few words: "needs 268 in, has 264 in".
// The room a check that fits has left, as its sentence says it: past the walkway or gaps, beside the mirrors, above the roof.
const spare = (check, fit) => check.key === 'racks' ? `${r(check.have - fit.rackBottom)} in under the ceiling` : `${r(Math.max(0, check.key === 'door_width' ? check.margin + ROOM.doorSide : check.key === 'door_height' ? check.margin + ROOM.doorHead : check.margin))} in to spare`;
const issue = (check, fit) => check.key === 'racks' ? `${r(check.have - fit.rackBottom)} in under the ceiling` : check.key === 'door_height' ? `${r(check.have - check.need + ROOM.doorHead)} in headroom` : `needs ${r(check.need)} in, has ${r(check.have)} in`;

/** The PARKING line of the briefs and the crew's "Parking after the job" (instructions.parkingPlan), at most 1,000
 * characters: the vehicles, the garage, what is tight, and the rack height limit. */
function planText(garage, vehicles, fit, options = {}) {
  const dims = (list, names) => list.every(d => !d.typical) ? ' measured' : list.every(d => d.typical) ? ' typical' : ` (measured: ${names.slice(0, list.length).filter((_, i) => !list[i].typical).join(', ')}; the rest typical)`;
  const door = garage.doors.reduce((a, b) => b.in > a.in ? b : a);
  const garageDims = [garage.width, garage.depth, door, garage.doorHeight, ...(options.racks ? [garage.ceiling] : [])];
  const parts = [vehicles.map(v => `${v.label} (${r(v.length_in)}×${r(v.width_in)}×${r(v.height_in)} in)`).join(' + ') + '.',
    `Garage ${r(garage.width.in)}×${r(garage.depth.in)} in, door ${r(door.in)}×${r(garage.doorHeight.in)} in${options.racks ? `, ceiling ${r(garage.ceiling.in)} in` : ''}${dims(garageDims, ['width', 'depth', 'door width', 'door height', 'ceiling'])}.`];
  const problems = fit.checks.filter(check => check.status !== 'fits');
  if (problems.length) parts.push(problems.map(check => `${check.label} ${STATUS_TEXT[check.status]} (${issue(check, fit)})`).join('; ') + '.');
  else { const t = tightest(fit); parts.push(`Everything fits; tightest is ${t.label.toLowerCase()} (${spare(t, fit)}).`); }
  parts.push(options.racks ? `Keep overhead racks ≥ ${fit.rackBottom} in off the floor.` : `Hang nothing lower than ${fit.rackBottom} in over the parked vehicles.`);
  if (fit.shelving) parts.push(`Shelving counted ${ROOM.shelf} in deep on the ${fit.shelving === 'back' ? 'back' : 'side'} wall.`);
  const unsure = vehicles.filter(v => v.measure).map(v => v.short);
  if (unsure.length) parts.push(`Measure to be sure: ${[...new Set(unsure)].join(', ')}.`);
  if (fit.overall !== 'fits' && problems.some(check => check.typical)) parts.push('Typical garage sizes there: measure before promising the fit.');
  const text = parts.join(' ');
  return text.length > PLAN_MAX ? `${text.slice(0, PLAN_MAX - 1).trimEnd()}…` : text;
}
const OVERALL = Object.freeze({ fits: 'Fits', tight: 'Tight', wont_fit: 'Won’t fit' });
function summaryText(vehicles, fit) {
  const t = tightest(fit);
  return `${vehicles.length} vehicle${vehicles.length === 1 ? '' : 's'} · ${OVERALL[fit.overall]}${fit.overall === 'fits' ? `; tightest: ${t.label.toLowerCase()}, ${spare(t, fit)}` : ` — ${t.label.toLowerCase()} ${issue(t, fit)}${t.typical ? ' (typical garage size: measure it)' : ''}`}`;
}

/** Everything the walkthrough sends about parking: null when there is nothing (no vehicles, nothing measured), so the
 * brief, the payload and Review are unchanged; {scope: {garage_measurements}} when only the garage was measured; else
 * the vehicles, the fit check, the plan text (parkingPlan), the Review summary and the scope fields. */
function parking({ vehicles, size, measure, racks = false, shelfWall = 'side', quote = {} } = {}) {
  const list = (Array.isArray(vehicles) ? vehicles : []).map(cleanVehicle).filter(Boolean).slice(0, MAX_VEHICLES), measured = measuredGarage(measure);
  if (!list.length) return measured ? { scope: { garage_measurements: measured } } : null;
  const garage = garageFrom(size, measure), options = { racks: quote.overhead === true || racks === true, shelving: quote.shelving === true ? (shelfWall === 'back' ? 'back' : 'side') : null };
  const fit = fitCheck(garage, list, options), text = planText(garage, list, fit, options);
  return { vehicles: list, garage, options, fit, text, summary: summaryText(list, fit),
    scope: { customer_vehicles: list.map(scopeVehicle), ...(measured ? { garage_measurements: measured } : {}), parking_plan: text } };
}

