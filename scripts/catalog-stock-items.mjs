/**
 * Stocked-item list for owner standard costs (FUN-19). Pages Functions read the catalog's active products
 * (id, name, category, priceUnit) from functions/_data/catalog-stock-items.js, a generated plain-JavaScript
 * module: a JSON import needs `with { type: 'json' }` in Node, which the esbuild in older Wrangler releases
 * cannot parse, and the full catalog is not needed to name the items. The catalog JSON stays the source.
 *   node scripts/catalog-stock-items.mjs            report; exit 1 when the module is stale
 *   node scripts/catalog-stock-items.mjs --write    rewrite functions/_data/catalog-stock-items.js
 * Read-only unless --write. Prices are deliberately left out: retail prices are never a cost.
 */
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';

export const REPO_ROOT=fileURLToPath(new URL('..',import.meta.url));
export const MODULE='functions/_data/catalog-stock-items.js';
export const SOURCE='functions/_data/garage-catalog.json';

export function stockItemsModule(catalogText){
  const catalog=JSON.parse(catalogText);
  const categories=catalog.categories.filter(category=>category.kind==='product').map(category=>[category.id,category.label]);
  const items=catalog.items.filter(item=>item.kind==='product'&&item.availability==='active').map(item=>[item.id,item.name,item.category,item.priceUnit]).sort((a,b)=>a[0].localeCompare(b[0]));
  return [
    `// Generated by scripts/catalog-stock-items.mjs from ${SOURCE}. Do not edit: change the JSON, then run`,
    '// node scripts/catalog-stock-items.mjs --write (tests/standard-costs.test.mjs fails while this file is stale).',
    '// Active catalog products an owner may give a standard unit cost: [id, name, category, priceUnit]. No prices.',
    `export const STOCK_CATALOG_VERSION = ${JSON.stringify(catalog.catalogVersion)};`,
    `export const STOCK_CATEGORIES = ${JSON.stringify(categories)};`,
    'export const STOCK_ITEMS = [',
    ...items.map(item=>`  ${JSON.stringify(item)},`),
    '];',
    '',
  ].join('\n');
}

export const expectedStockItemsModule=(root=REPO_ROOT)=>stockItemsModule(readFileSync(join(root,SOURCE),'utf8'));

function main(){
  const write=process.argv.includes('--write'),path=join(REPO_ROOT,MODULE),expected=expectedStockItemsModule();
  if(write)writeFileSync(path,expected);
  const stale=!existsSync(path)||readFileSync(path,'utf8')!==expected;
  console.log(stale?`✗ ${MODULE} is stale; run node scripts/catalog-stock-items.mjs --write`:`${MODULE} matches the catalog JSON${write?' (written)':''}`);
  if(stale)process.exitCode=1;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href)main();
