/**
 * Funnel definitions sync and drift check (FUN-01). The canonical file is
 * functions/_data/funnel-definitions.data.json. Two copies are generated from it:
 *   functions/_lib/funnel-definitions.data.js                       the Hub runtime copy (exact JSON text)
 *   egc-platform/packages/funnel-definitions/funnel-definitions.data.json   the platform package copy (byte-identical)
 * plus egc-platform/packages/funnel-definitions/src/generated.ts, which pins the
 * Hub-computed definitionsHash so the platform proves it hashes the same way.
 *   node scripts/funnel-definitions.mjs            check (default): exit 1 on drift or invalid definitions
 *   node scripts/funnel-definitions.mjs --check    same
 *   node scripts/funnel-definitions.mjs --write    validate, then regenerate the three files
 * Prints `funnel definitions <version> <definitionsHash>`. Read-only unless --write.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
export const FUNNEL_DEFINITION_PATHS = Object.freeze({
  canonical: 'functions/_data/funnel-definitions.data.json',
  hubModule: 'functions/_lib/funnel-definitions.data.js',
  platformJson: 'egc-platform/packages/funnel-definitions/funnel-definitions.data.json',
  platformHash: 'egc-platform/packages/funnel-definitions/src/generated.ts',
});
const main = import.meta.url === pathToFileURL(process.argv[1] || '').href, args = main ? process.argv.slice(2) : [];
if (args.some(arg => !['--check', '--write'].includes(arg))) { console.error('Usage: node scripts/funnel-definitions.mjs [--check|--write]'); process.exit(2); }
// The hashing and validation helpers live in the Hub module, which statically
// imports its generated copy. Only --write restores a deleted copy (as an empty
// stub that it then regenerates); a check reports it as drift, and neither a
// check nor an import of this file ever writes.
const hubModule = join(REPO_ROOT, FUNNEL_DEFINITION_PATHS.hubModule);
if (main && !existsSync(hubModule)) {
  if (!args.includes('--write')) { console.error(`drift: ${FUNNEL_DEFINITION_PATHS.hubModule} missing. Run node scripts/funnel-definitions.mjs --write and commit the result.`); process.exit(1); }
  writeFileSync(hubModule, 'export default "";\n');
}
const { canonicalJson, sha256Hex, validateFunnelDefinitions } = await import('../functions/_lib/funnel-definitions.js');

/** The exact generated files for the canonical text, plus its version and hash. */
export function funnelDefinitionOutputs(text) {
  if (typeof text !== 'string' || text.charCodeAt(0) === 0xfeff) throw new Error('The canonical funnel definitions must be UTF-8 JSON without a byte-order mark.');
  let parsed;
  try { parsed = JSON.parse(text); } catch { throw new Error('The canonical funnel definitions are not valid JSON.'); }
  const problems = validateFunnelDefinitions(parsed);
  if (problems.length) throw new Error(`The canonical funnel definitions are invalid:\n- ${problems.join('\n- ')}`);
  const hash = sha256Hex(canonicalJson(parsed)), version = parsed.definitionsVersion;
  const banner = 'GENERATED by `node scripts/funnel-definitions.mjs --write` from functions/_data/funnel-definitions.data.json. Do not edit.';
  return {
    hash, version,
    files: {
      [FUNNEL_DEFINITION_PATHS.hubModule]: `// ${banner}\n// The drift check fails when this text differs from the canonical JSON.\nexport default ${JSON.stringify(text)};\n`,
      [FUNNEL_DEFINITION_PATHS.platformJson]: text,
      [FUNNEL_DEFINITION_PATHS.platformHash]: `// ${banner}\n// definitionsHash as computed by the Hub (functions/_lib/funnel-definitions.js); src/index.test.ts proves the platform computes the same value.\nexport const hubDefinitionsHash = ${JSON.stringify(hash)};\nexport const hubDefinitionsVersion = ${JSON.stringify(version)};\n`,
    },
  };
}

/** Lists every generated file that is missing or differs from the canonical JSON. */
export function funnelDefinitionsDrift(root = REPO_ROOT) {
  const outputs = funnelDefinitionOutputs(readFileSync(join(root, FUNNEL_DEFINITION_PATHS.canonical), 'utf8'));
  const drift = [];
  for (const [path, content] of Object.entries(outputs.files)) {
    const file = join(root, path);
    if (!existsSync(file)) drift.push({ path, reason: 'missing' });
    else if (readFileSync(file, 'utf8') !== content) drift.push({ path, reason: 'differs from the canonical JSON' });
  }
  return { hash: outputs.hash, version: outputs.version, drift };
}

export function writeFunnelDefinitions(root = REPO_ROOT) {
  const outputs = funnelDefinitionOutputs(readFileSync(join(root, FUNNEL_DEFINITION_PATHS.canonical), 'utf8'));
  for (const [path, content] of Object.entries(outputs.files)) writeFileSync(join(root, path), content);
  return outputs;
}

if (main) {
  try {
    if (args.includes('--write')) writeFunnelDefinitions();
    const { hash, version, drift } = funnelDefinitionsDrift();
    console.log(`funnel definitions ${version} ${hash}`);
    for (const item of drift) console.error(`drift: ${item.path} ${item.reason}. Run node scripts/funnel-definitions.mjs --write and commit the result.`);
    process.exit(drift.length ? 1 : 0);
  } catch (error) { console.error(error.message); process.exit(1); }
}
